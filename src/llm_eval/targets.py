"""Systems under test. Anything with ``name`` and ``answer(question) -> TargetResponse`` works.

- ``ExtractiveRAG``: offline lexical-retrieval + extractive answering baseline (no API key).
- ``HallucinatingRAG``: same, but injects an unsupported claim — used to prove the gate catches regressions.
- ``LLMRAG``: same retriever, answer generated by any OpenAI-compatible model.
- ``HTTPTarget``: black-box evaluate your own deployed endpoint.
"""

from __future__ import annotations

import json
import math
import time
from collections import Counter
from pathlib import Path
from typing import Protocol

import httpx

from .llm import ChatClient
from .models import TargetResponse
from .text import sentences, tokens

REFUSAL = "I don't know - that is not covered in the provided documents."


class Target(Protocol):
    name: str

    def answer(self, question: str) -> TargetResponse: ...


class BM25:
    def __init__(self, docs: list[str], k1: float = 1.5, b: float = 0.75) -> None:
        self.docs = docs
        self.k1, self.b = k1, b
        self.tok = [tokens(d, drop_stopwords=True) for d in docs]
        self.avgdl = sum(map(len, self.tok)) / max(len(self.tok), 1)
        df: Counter = Counter()
        for t in self.tok:
            df.update(set(t))
        n = len(docs)
        self.idf = {w: math.log(1 + (n - f + 0.5) / (f + 0.5)) for w, f in df.items()}

    def search(self, query: str, k: int = 3) -> list[tuple[int, float]]:
        q = tokens(query, drop_stopwords=True)
        scores = []
        for i, doc in enumerate(self.tok):
            tf = Counter(doc)
            s = 0.0
            for w in q:
                if w in tf:
                    num = tf[w] * (self.k1 + 1)
                    den = tf[w] + self.k1 * (1 - self.b + self.b * len(doc) / self.avgdl)
                    s += self.idf[w] * num / den
            scores.append((i, s))
        return sorted(scores, key=lambda x: -x[1])[:k]


def load_kb(path: str | Path) -> list[str]:
    with open(path, encoding="utf-8") as f:
        return [json.loads(line)["text"] for line in f if line.strip()]


class ExtractiveRAG:
    name = "extractive-rag"

    def __init__(self, kb: list[str], k: int = 2, min_score: float = 3.0) -> None:
        self.index = BM25(kb)
        self.k, self.min_score = k, min_score

    def retrieve(self, question: str) -> list[str]:
        hits = self.index.search(question, self.k)
        return [self.index.docs[i] for i, s in hits if s >= self.min_score]

    def _best_sentence(self, question: str, contexts: list[str]) -> str:
        q = set(tokens(question, drop_stopwords=True))
        cands = [s for c in contexts for s in sentences(c)]
        return max(cands, key=lambda s: len(q & set(tokens(s, drop_stopwords=True))))

    def answer(self, question: str) -> TargetResponse:
        t0 = time.perf_counter()
        contexts = self.retrieve(question)
        text = self._best_sentence(question, contexts) if contexts else REFUSAL
        return TargetResponse(answer=text, contexts=contexts, latency_ms=(time.perf_counter() - t0) * 1000)


class HallucinatingRAG(ExtractiveRAG):
    """Simulates a bad prompt/model change: answers without context and adds a made-up figure."""

    name = "hallucinating-rag"

    def answer(self, question: str) -> TargetResponse:
        resp = super().answer(question)
        if not resp.contexts:
            resp.answer = "Yes, this is allowed for up to 97% of the loan amount."
        else:
            resp.answer += " Borrowers with a score above 780 also receive an automatic 0.5% rate discount."
        return resp


SYSTEM_PROMPT = (
    "Answer using ONLY the context. Be concise (1-2 sentences). If the context does not "
    f"contain the answer, reply exactly: {REFUSAL}"
)


class LLMRAG(ExtractiveRAG):
    def __init__(self, kb: list[str], client: ChatClient | None = None, **kw) -> None:
        super().__init__(kb, **kw)
        self.client = client or ChatClient()
        self.name = f"llm-rag:{self.client.model}"

    def answer(self, question: str) -> TargetResponse:
        t0 = time.perf_counter()
        contexts = self.retrieve(question)
        ctx = "\n\n".join(f"[{i + 1}] {c}" for i, c in enumerate(contexts)) or "(none)"
        text = self.client.chat(
            [
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": f"Context:\n{ctx}\n\nQuestion: {question}"},
            ]
        )
        return TargetResponse(answer=text.strip(), contexts=contexts, latency_ms=(time.perf_counter() - t0) * 1000)


class HTTPTarget:
    """POSTs {"question": ...} and expects {"answer": str, "contexts": [str]}."""

    def __init__(self, url: str, timeout: float = 60.0) -> None:
        self.url = url
        self.name = f"http:{url}"
        self._http = httpx.Client(timeout=timeout)

    def answer(self, question: str) -> TargetResponse:
        t0 = time.perf_counter()
        r = self._http.post(self.url, json={"question": question})
        r.raise_for_status()
        data = r.json()
        return TargetResponse(
            answer=data["answer"],
            contexts=data.get("contexts", []),
            latency_ms=(time.perf_counter() - t0) * 1000,
        )
